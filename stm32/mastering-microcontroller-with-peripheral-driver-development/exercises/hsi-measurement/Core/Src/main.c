/* HSI16 / 4 = 4 MHz on PA8 (MCO, AF0): Arduino D7, CN9 pin 8.
 * Divided by 4 because PA8 resets to low speed, rated 5 MHz at 50 pF (DS10198 Table 72). */
static void mco_output_hsi16(void)
{
  /* 1. HSI16 is off at reset on the L4: it boots on MSI 4 MHz (RCC_CR resets to 0x63) */
  MY_RCC_CR |= (1UL << 8); /* HSION */
  while (!(MY_RCC_CR & (1UL << 10))) /* HSIRDY */
  {
  }

  /* 2. Prescaler first: RM0351 asks for it to be set before MCO is enabled */
  MY_RCC_CFGR &= ~(0x7UL << 28); /* MCOPRE */
  MY_RCC_CFGR |= (0x2UL << 28);  /* 010: divide by 4 */
  MY_RCC_CFGR &= ~(0xFUL << 24); /* MCOSEL */
  MY_RCC_CFGR |= (0x3UL << 24);  /* 0011: HSI16 */

  /* 3. GPIOA clock; reading it back is the delay RM0351 requires before touching GPIOA */
  MY_RCC_AHB2ENR |= (1UL << 0); /* GPIOAEN */
  (void)MY_RCC_AHB2ENR;

  /* 4. PA8 -> alternate function 0 (MCO, DS10198 Table 17) */
  MY_GPIOA_MODER &= ~(0x3UL << 16);
  MY_GPIOA_MODER |= (0x2UL << 16); /* 10: alternate function */
  MY_GPIOA_AFRH &= ~(0xFUL << 0);  /* AFSEL8 = 0000: AF0 */
}
